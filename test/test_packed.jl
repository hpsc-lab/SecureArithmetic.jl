# `PlainArrayPacked(data, context)` packs in the clear, before encoding, so it is free.
# `SecureArrayPacked(::SecureArray)` has to rebuild the same layout homomorphically, from
# masks and rotations. These cases pin that the two agree slot for slot, and that the
# conversion costs what `SecureArrayPacked` claims it costs.
#
# Every case gets a fresh context in which only `init_packing!` ran, so a shift the
# conversion performs but `compute_packing_shifts` does not report makes these tests fail -
# the same guard that `packed_mat_mat_mul` provides for the multiplication kernel.
@testset verbose=true showtiming=true "repacking an encrypted array" begin
    # The batch size is 16, so dimensions longer than 4 are cut into blocks. The expected
    # level is what OpenFHE *reports*: under FLEXIBLEAUTO the rescale of a multiplication is
    # deferred to the next one, so `level` lags the consumed depth by one. The conversion
    # performs at most one multiplication: every block lives in a ciphertext of its own, so no
    # rotation is masked.
    for (shape, want_level) in [((4, 4), 0),   # fast path: already a packed block
                                ((8, 2), 0),   # 2x1 blocks of 4x2
                                ((16,), 0),    # vector, 4 blocks
                                ((4, 2), 0),   # D == d, tiled, so mask but no rotation
                                ((3, 3), 0),   # D > d, single ciphertext
                                ((5, 2), 0),   # 2x1 blocks of 4x2
                                ((6,), 0),     # vector, 2 blocks
                                ((6, 4), 0),   # 2x1 blocks of 4x4
                                ((5, 5), 0)]   # 2x2 blocks of 4x4
        @testset "$shape" begin
            Random.seed!(3141)
            (context, public_key, private_key) = make_context()

            data = rand(shape...)
            unpacked = encrypt(PlainArray(data, context), public_key)
            init_packing!(context, private_key, shape)

            packed = SecureArrayPacked(unpacked)
            reference = PlainArrayPacked(data, context)

            @test packed isa SecureArrayPacked
            @test collect(decrypt(packed, private_key)) ≈ data

            # The layout invariants of a packed array, as in "packing layout" above
            @test size(packed) == shape
            @test packed.padded_shape == reference.padded_shape
            @test capacity(packed) == length(packed.array)
            @test capacity(packed) == SecureArithmetic.n_blocks(packed) *
                                      SecureArithmetic.n_tiles(packed) *
                                      prod(packed.padded_shape)
            @test capacity(packed) == capacity(reference)

            # Agreement with clear-side packing is asserted on the whole storage, not just on
            # the cropped data: the padding and the tiles have to be zero and faithful too
            storage = vec(collect(decrypt(packed.array, private_key)))
            @test storage ≈ vec(collect(reference.array))

            tiles = reshape(storage, prod(packed.padded_shape), :, SecureArithmetic.n_blocks(packed))
            @test size(tiles, 2) == SecureArithmetic.n_tiles(packed)
            for b in axes(tiles, 3), j in axes(tiles, 2)
                @test tiles[:, j, b] ≈ tiles[:, 1, b]
            end

            @test level(packed) == want_level

            release_context_memory()
            GC.gc()
        end
    end
end

# The `capacity - length` tail of an unpacked array is zero for a freshly encrypted one, but
# the masked rotation path writes data straight through it, and `resize` clones the first
# ciphertext into the slots it adds. A conversion that trusted either of those to be zero
# passes every case above and fails this one.
@testset verbose=true showtiming=true "repacking does not trust the unused slots" begin
    Random.seed!(3141)
    shape = (3, 3)
    (context, public_key, private_key) = make_context()

    data = rand(shape...)
    unpacked = encrypt(PlainArray(data, context), public_key)

    # Rotate and rotate back, which leaves the slots past `length` holding data
    init_rotation!(context, private_key, shape, (1, 0), (-1, 0))
    dirtied = circshift(circshift(unpacked, (1, 0)), (-1, 0))
    @test collect(decrypt(dirtied, private_key)) ≈ data

    init_packing!(context, private_key, shape)
    packed = SecureArrayPacked(dirtied)

    @test collect(decrypt(packed, private_key)) ≈ data
    @test vec(collect(decrypt(packed.array, private_key))) ≈
          vec(collect(PlainArrayPacked(data, context).array))

    release_context_memory()
    GC.gc()
end

# What the conversion is for: an operand that is already encrypted and unpacked can reach the
# packed kernel, which is both cheaper and free of the `l | d` restriction of the unpacked one.
@testset verbose=true showtiming=true "repacked operands can be multiplied" begin
    Random.seed!(3141)

    for (d, l) in [(4, 4),   # square
                   (4, 2),   # rectangular
                   (6, 4),   # l = 4 does not divide d = 6
                   (5, 3)]   # neither dimension is a power of two
        @testset "$(d)x$(d) * $(d)x$(l)" begin
            (context, public_key, private_key) = make_context()

            # Keep the product small, as the chained-product cases above do: the default
            # scaling modulus leaves little headroom in the last modulus of the chain
            m1 = rand(d, d) ./ 4
            m2 = rand(d, l) ./ 4

            pm1 = PlainArrayPacked(m1, context)
            unpacked = encrypt(PlainArray(m2, context), public_key)
            init_packing!(context, private_key, size(m2))
            init_multiplication!(context, private_key)

            repacked = SecureArrayPacked(unpacked)
            init_matrix_multiplication!(context, private_key, size(pm1), size(repacked);
                                        packed = true)

            @test collect(decrypt(pm1 * repacked, private_key)) ≈ m1 * m2

            release_context_memory()
            GC.gc()
        end
    end
end

# The level assertions above are about what OpenFHE reports; this is about the multiplicative
# budget the conversion actually consumes, which is what a caller has to size its context for.
@testset verbose=true showtiming=true "repacking depth" begin
    Random.seed!(3141)
    mod_sizes = (scaling_mod_size = 50, first_mod_size = 60)

    # A packed square product needs a depth of 3 by itself, see "packed multiplicative depth".
    # The default batch size of 16 is what puts `d = 4` on the fast path: its padded block is
    # exactly one ciphertext, so there is nothing to tile and nothing to zero.
    for (d, depth) in [(4, 3),   # fast path: the conversion is free, so still 3
                       (3, 4)]   # one mask, so one more than the product alone
        @testset "$(d)x$(d) at depth $depth" begin
            (context, public_key, private_key) = make_context(; depth, mod_sizes...)
            m1 = rand(d, d)
            m2 = rand(d, d)

            pm1 = PlainArrayPacked(m1, context)
            unpacked = encrypt(PlainArray(m2, context), public_key)
            init_packing!(context, private_key, size(m2))
            init_multiplication!(context, private_key)

            repacked = SecureArrayPacked(unpacked)
            init_matrix_multiplication!(context, private_key, size(pm1), size(repacked);
                                        packed = true)

            @test collect(decrypt(pm1 * repacked, private_key)) ≈ m1 * m2

            release_context_memory()
            GC.gc()
        end
    end
end

# `SecureArray(::SecureArrayPacked)` is the inverse of the conversion above: it drops the zero
# padding and the tiling, so that the result is laid out exactly like a freshly encrypted flat
# array. These cases pin that round trip and what it costs. This is the conversion `*` applies to
# the result of a product of flat operands.
#
# Every case gets a fresh context in which only `init_unpacking!` ran, so a shift the conversion
# performs but `compute_unpacking_shifts` does not report makes these tests fail.
@testset verbose=true showtiming=true "unpacking an encrypted array" begin
    # The batch size is 16. Unpacking is a pure relabelling whenever the unpadded data already
    # is a contiguous prefix of the padded block, i.e. when the first dimension needs no padding
    # and for any vector; otherwise it masks, which costs a level - also with several blocks,
    # because every block lives in a ciphertext of its own and no rotation is masked. As above,
    # the expected level is what OpenFHE *reports*, which lags the consumed depth by one under
    # FLEXIBLEAUTO.
    for (shape, want_level) in [((4, 4), 0),   # relabelling: no padding at all
                                ((8, 2), 0),   # 2x1 blocks of 4x2
                                ((16,), 0),    # vector, 4 blocks
                                ((6,), 0),     # vector, 2 blocks
                                ((4, 2), 0),   # relabelling: D == d, tiled
                                ((3, 1), 0),   # relabelling: single run, d x 1
                                ((3, 3), 0),   # D > d, single ciphertext: masked, level-free
                                ((5, 2), 0),   # 2x1 blocks of 4x2
                                ((5, 5), 0),   # 2x2 blocks of 4x4
                                ((6, 4), 0)]   # 2x1 blocks of 4x4, rectangular
        @testset "$shape" begin
            Random.seed!(3141)
            (context, public_key, private_key) = make_context()

            data = rand(shape...)
            packed = encrypt(PlainArrayPacked(data, context), public_key)
            init_unpacking!(context, private_key, shape)

            flat = SecureArray(packed)
            reference = encrypt(PlainArray(data, context), public_key)

            @test flat isa SecureArray
            @test size(flat) == shape
            @test ndims(flat) == length(shape)
            @test length(flat) == prod(shape)
            @test capacity(flat) == capacity(reference)
            @test collect(decrypt(flat, private_key)) ≈ data
            @test level(flat) == want_level

            release_context_memory()
            GC.gc()
        end
    end
end

# A product of flat operands packs, multiplies and unpacks, so the round trip has to be exact
# for the shapes a result can have - including the ones the matrix kernel leaves in a larger
# storage than the shape itself needs, which the conversion normalizes first.
@testset verbose=true showtiming=true "packing round trip" begin
    for shape in [(4, 4), (5, 5), (6, 3), (3,), (6,), (1, 1), (17, 2)]
        @testset "$shape" begin
            Random.seed!(3141)
            (context, public_key, private_key) = make_context()

            data = rand(shape...)
            init_packing!(context, private_key, shape)
            init_unpacking!(context, private_key, shape)

            flat = encrypt(PlainArray(data, context), public_key)
            roundtrip = SecureArray(SecureArrayPacked(flat))

            @test size(roundtrip) == shape
            @test collect(decrypt(roundtrip, private_key)) ≈ data

            # The plaintext round trip is free and must agree exactly
            @test collect(PlainArray(PlainArrayPacked(data, context))) ≈ data

            release_context_memory()
            GC.gc()
        end
    end
end

# `slot_count` is 1 for the unencrypted backend, so a packed array is never tiled - the round
# trip still has to hold there.
@testset verbose=true showtiming=true "unpacking on Unencrypted backend" begin
    context = SecureContext(Unencrypted())
    public_key, private_key = generate_keys(context)

    for shape in [(4, 4), (5, 5), (8, 2), (6, 4), (17, 17), (6,)]
        data = rand(shape...)

        @test collect(PlainArray(PlainArrayPacked(data, context))) ≈ data

        flat = encrypt(PlainArray(data, context), public_key)
        roundtrip = SecureArray(SecureArrayPacked(flat))
        @test size(roundtrip) == shape
        @test collect(decrypt(roundtrip, private_key)) ≈ data
    end
end

# Converting a plaintext needs no homomorphic work at all - it is decoded, padded and tiled in
# the clear - so it has to agree with `PlainArrayPacked(data, context)` exactly.
@testset verbose=true showtiming=true "repacking a plain array" begin
    Random.seed!(3141)

    for (backend_name, context) in (("Unencrypted", SecureContext(Unencrypted())),
                                    ("OpenFHEBackend", make_context()[1]))
        @testset "$backend_name" begin
            for shape in ((4, 4), (5, 3), (6, 4), (7,))
                data = rand(shape...)
                converted = PlainArrayPacked(PlainArray(data, context))
                reference = PlainArrayPacked(data, context)

                @test collect(converted) ≈ data
                @test converted.padded_shape == reference.padded_shape
                @test vec(collect(converted.array)) ≈ vec(collect(reference.array))
            end
        end
    end

    release_context_memory()
    GC.gc()
end

# `slot_count` is 1 for the unencrypted backend, so the padded block is never tiled and the
# storage is always exactly one block.
@testset verbose=true showtiming=true "repacking on Unencrypted backend" begin
    Random.seed!(3141)
    context = SecureContext(Unencrypted())
    public_key, private_key = generate_keys(context)

    for shape in [(4, 4), (4, 2), (3, 3), (5, 5), (6, 4), (17, 17), (6,), (8,)]
        @testset "$shape" begin
            data = rand(shape...)
            unpacked = encrypt(PlainArray(data, context), public_key)
            init_packing!(context, private_key, shape)

            packed = SecureArrayPacked(unpacked)
            reference = PlainArrayPacked(data, context)

            @test collect(decrypt(packed, private_key)) ≈ data
            @test packed.padded_shape == reference.padded_shape
            @test capacity(packed) == capacity(reference)
            @test vec(collect(decrypt(packed.array, private_key))) ≈
                  vec(collect(reference.array))
        end
    end

    for (d, l) in [(6, 4), (5, 3)]
        @testset "$(d)x$(d) * $(d)x$(l)" begin
            m1 = rand(d, d)
            m2 = rand(d, l)

            pm1 = PlainArrayPacked(m1, context)
            unpacked = encrypt(PlainArray(m2, context), public_key)
            init_packing!(context, private_key, size(m2))

            repacked = SecureArrayPacked(unpacked)
            init_matrix_multiplication!(context, private_key, size(pm1), size(repacked);
                                        packed = true)

            @test collect(decrypt(pm1 * repacked, private_key)) ≈ m1 * m2
        end
    end
end

